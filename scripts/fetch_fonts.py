"""Download the site's fonts from Google Fonts once and serve them from the site itself.

Self-hosting means visitors' browsers never contact Google, pages render without a
third-party request, and the site keeps working if Google Fonts changes.
Only the Latin and Latin Extended character sets are kept (enough for every name in the data).

  py -P scripts/fetch_fonts.py     writes site/assets/fonts/*.woff2, site/assets/fonts/licenses/,
                                   and site/assets/css/fonts.css

All five families are under the SIL Open Font License 1.1, which allows bundling with a website
as long as the license travels with the fonts (see site/assets/fonts/licenses/).
"""
import hashlib
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "site", "assets", "fonts")
CSS_OUT = os.path.join(ROOT, "site", "assets", "css", "fonts.css")

# Same families, axes and weights the site has used since M3.
API = ("https://fonts.googleapis.com/css2?family=Archivo:ital,wdth,wght@0,62..125,400..900;1,62..125,400..900"
       "&family=Barlow+Condensed:wght@500;600;700;800&family=Inter:wght@400;500;600;700"
       "&family=Source+Serif+4:opsz,wght@8..60,400..800&family=Zilla+Slab:wght@500;600;700&display=swap")
LICENSES = {  # family -> folder in github.com/google/fonts
    "Archivo": "archivo", "Barlow Condensed": "barlowcondensed", "Inter": "inter",
    "Source Serif 4": "sourceserif4", "Zilla Slab": "zillaslab",
}
KEEP = {"latin", "latin-ext"}
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    os.makedirs(os.path.join(FONTS, "licenses"), exist_ok=True)
    css = get(API).decode("utf-8")
    blocks = re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S)
    out, saved, total = [], {}, 0
    for subset, block in blocks:
        if subset not in KEEP:
            continue
        family = re.search(r"font-family: '([^']+)'", block).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        if url not in saved:
            data = get(url)
            style = re.search(r"font-style: (\w+)", block).group(1)
            name = f"{family.lower().replace(' ', '-')}-{style}-{subset}-{hashlib.sha1(url.encode()).hexdigest()[:6]}.woff2"
            with open(os.path.join(FONTS, name), "wb") as f:
                f.write(data)
            saved[url] = name
            total += len(data)
        out.append(f"/* {family}, {subset} */\n" + block.replace(url, "../fonts/" + saved[url]))
    for family, folder in LICENSES.items():
        text = get(f"https://raw.githubusercontent.com/google/fonts/main/ofl/{folder}/OFL.txt")
        with open(os.path.join(FONTS, "licenses", f"{folder}-OFL.txt"), "wb") as f:
            f.write(text)
    header = ("/* Self-hosted fonts (generated by scripts/fetch_fonts.py from Google Fonts; do not edit).\n"
              "   Licenses: assets/fonts/licenses/ (SIL Open Font License 1.1). */\n\n")
    with open(CSS_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n\n".join(out) + "\n")
    print(f"{len(out)} @font-face rules, {len(saved)} files, {total / 1024:.0f} KB; licenses for {len(LICENSES)} families")


if __name__ == "__main__":
    main()
